/**
 * Mirrors the released package's changelog to the repo root.
 *
 * changesets hardcodes the changelog to `<packageDir>/CHANGELOG.md` (see
 * apply-release-plan), so a root-level one has to be copied. Runs as part of
 * `npm run version`, which is what the release workflow calls — so the copy lands
 * in the same "chore: release" PR as the entry it mirrors.
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE = path.join(ROOT, "apps", "ocean-viewer", "CHANGELOG.md");
const TARGET = path.join(ROOT, "CHANGELOG.md");

const BANNER = `<!--
  Generated by scripts/sync-changelog.js — do not edit.
  Add entries with \`npx changeset\`; see CONTRIBUTING.md.
-->
`;

let source;
try {
	source = await readFile(SOURCE, "utf8");
} catch (err) {
	if (err.code === "ENOENT") {
		// No release has been cut yet.
		console.log(`No ${path.relative(ROOT, SOURCE)} yet — nothing to sync.`);
		process.exit(0);
	}
	throw err;
}

await writeFile(TARGET, `${BANNER}\n${source.trimStart()}`);
console.log(`Synced ${path.relative(ROOT, SOURCE)} → CHANGELOG.md`);
